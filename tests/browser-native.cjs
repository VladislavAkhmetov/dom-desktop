const { app, BrowserWindow, ipcMain } = require('electron')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const http = require('node:http')
const { createStorage } = require('../electron/storage.cjs')
const { BrowserManager } = require('../electron/browser.cjs')
const directory = path.resolve(__dirname, '../.cache/browser-tests', String(Date.now()))
fs.mkdirSync(directory, { recursive: true })
app.setPath('userData', directory)
let window, storage, manager, server
app.on('window-all-closed', () => undefined)
const waitFor = async (test, label) => { const end = Date.now() + 12000; while (Date.now() < end) { if (await test()) return; await new Promise(resolve => setTimeout(resolve, 100)) } throw new Error(`Ожидание: ${label}`) }
async function run() {
  server = http.createServer((_request, response) => { response.setHeader('Content-Type', 'text/html; charset=utf-8'); response.end('<!doctype html><title>Проверочная страница</title><body><h1>Рабочая страница</h1><form><label>Несохранённый текст <input id="draft"></label></form><div style="height:1800px">Материал</div></body>') })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const port = server.address().port
  const tabs = Array.from({ length: 300 }, (_, index) => ({ id: `tab-${index}`, title: `Материал ${index + 1}`, url: `http://127.0.0.1:${port}/${index}` }))
  fs.writeFileSync(path.join(directory, 'state.json'), JSON.stringify({ version: 1, spaces: [{ id: 'space', name: 'Проект', tone: 'sage', resources: [], activeSession: { tabs, activeTabId: tabs[0].id } }], reminders: [], dismissedUntil: null }))
  storage = createStorage(directory); await storage.ready
  window = new BrowserWindow({ show: false, width: 1280, height: 720, titleBarStyle: 'hidden', webPreferences: { preload: path.join(__dirname, '../electron/preload.cjs'), contextIsolation: true, sandbox: true } })
  manager = new BrowserManager(window)
  window.webContents.on('console-message', event => { if (event.level === 'error') console.error('Renderer:', event.message) })
  ipcMain.handle('state:get', () => storage.get())
  ipcMain.handle('state:apply', async (_event, changes) => { const state = await storage.apply(changes); window.webContents.send('state:changed', state); return state })
  ipcMain.handle('state:search', (_event, query) => storage.search(query))
  ipcMain.handle('settings:getAutostart', () => false)
  ipcMain.handle('google:configured', () => false)
  ipcMain.handle('browser:show', (_event, value) => manager.show(value))
  ipcMain.handle('browser:hide', (_event, id) => manager.hide(id))
  ipcMain.handle('browser:block', (_event, value) => manager.block(value))
  ipcMain.handle('browser:close', (_event, id) => manager.close(id))
  ipcMain.handle('browser:park', (_event, ids) => manager.park(ids))
  ipcMain.handle('browser:action', (_event, id, action) => manager.action(id, action))
  ipcMain.on('page:signal', (event, value) => manager.pageSignal(event.sender, value))
  await window.loadFile(path.join(__dirname, '../dist/index.html'))
  await waitFor(() => window.webContents.executeJavaScript('Boolean(document.querySelector(".browser-chrome"))'), 'главная')
  await window.webContents.executeJavaScript('document.querySelector(".chrome-actions > button").click()')
  await waitFor(() => manager.tabs.size === 1, 'первая вкладка')
  const first = manager.tabs.get('tab-0')
  await waitFor(() => first.view.webContents.executeJavaScript('Boolean(document.querySelector("#draft"))').catch(() => false), 'сайт')
  assert.ok(first.bounds.height >= window.getContentBounds().height * 0.85, `Страница занимает ${first.bounds.height} из ${window.getContentBounds().height}px`)
  assert.equal(manager.tabs.size, 1, 'Не загрузились остальные 299 страниц')
  await first.view.webContents.executeJavaScript('document.querySelector("#draft").value="Сохранённый при переключении текст"; document.querySelector("#draft").dispatchEvent(new Event("input",{bubbles:true}))')
  await waitFor(() => first.protected, 'защита формы')
  await window.webContents.executeJavaScript('document.querySelectorAll(".vertical-tabs [role=tab]")[1].click()')
  await waitFor(() => manager.tabs.size === 2, 'вторая вкладка')
  assert.equal(await first.view.webContents.executeJavaScript('document.querySelector("#draft").value'), 'Сохранённый при переключении текст')
  await window.webContents.executeJavaScript('document.querySelector("[aria-label=Настройки]").click()')
  await waitFor(() => manager.blocked, 'модальный слой')
  assert.equal([...manager.tabs.values()].filter(record => record.view.getVisible()).length, 0)
  await window.webContents.executeJavaScript('document.querySelector(".modal-close").click()')
  await waitFor(() => !manager.blocked, 'возврат страницы после диалога')
  await window.webContents.executeJavaScript('document.querySelector(".brand").click()')
  await waitFor(() => [...manager.tabs.values()].every(record => !record.desired), 'возврат домой')
  assert.equal(await first.view.webContents.executeJavaScript('document.querySelector("#draft").value'), 'Сохранённый при переключении текст')
  const result = await manager.park(['tab-0', 'tab-1'])
  assert.equal(result.protectedCount, 1)
  assert.equal(manager.tabs.size, 1)
  console.log(`Electron: 300 вкладок, ленивая загрузка, сохранение формы, диалоги, главная и защита при уборке — OK; высота страницы ${first.bounds.height}px`)
}
app.whenReady().then(run).then(async () => { manager.dispose(); window.destroy(); await storage.close(); server.close(); app.exit(0) }).catch(async error => { console.error(error); manager?.dispose(); window?.destroy(); await storage?.close(); server?.close(); app.exit(1) })
