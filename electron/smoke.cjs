const assert = require('node:assert/strict')
const { BrowserWindow } = require('electron')
const path = require('node:path')
const fs = require('node:fs')
const waitFor = async (test, label) => { const end = Date.now() + 15000; while (Date.now() < end) { if (await test()) return; await new Promise(resolve => setTimeout(resolve, 100)) } throw new Error(`Проверка запуска: ${label}`) }
module.exports = async ({ window, storage, vault, showCapture, getCapture }) => {
  await waitFor(() => window.webContents.executeJavaScript('Boolean(document.querySelector(".browser-chrome"))').catch(() => false), 'главная')
  const state = await window.webContents.executeJavaScript('window.dom.getState()')
  assert.equal(state.version, 2)
  const exists = state.reminders.some(item => item.id === 'smoke-task')
  if (!exists) await window.webContents.executeJavaScript('window.dom.applyChanges([{op:"set",path:["reminders","@smoke-task"],value:{id:"smoke-task",title:"Проверка перезапуска",kind:"note",createdAt:new Date().toISOString(),dueAt:null,done:false}}])')
  assert.ok((await storage.get()).reminders.some(item => item.id === 'smoke-task'))
  assert.equal(await window.webContents.executeJavaScript('window.dom.integrations.googleConfigured()'), false)
  vault.set('smoke-key', 'fixture-encryption-check')
  assert.equal(vault.get('smoke-key'), 'fixture-encryption-check')
  assert.ok(!fs.readFileSync(vault.file, 'utf8').includes('fixture-encryption-check'))
  vault.set('smoke-key', undefined)
  const foreign = new BrowserWindow({ show: false, webPreferences: { preload: path.join(__dirname, 'preload.cjs'), contextIsolation: true, sandbox: true } })
  await foreign.loadURL('data:text/html,<title>Foreign</title>')
  const denied = await foreign.webContents.executeJavaScript('window.dom.getState().then(()=>false,()=>true)')
  assert.equal(denied, true, 'Чужое окно не получает доступ к данным')
  foreign.destroy()
  await showCapture(); const capture = getCapture(); capture.hide()
  await waitFor(() => capture.webContents.executeJavaScript('Boolean(document.querySelector("#quick-thought"))').catch(() => false), 'глобальная запись')
  await capture.webContents.executeJavaScript('document.querySelector("#quick-thought").value="Проверка глобальной записи"; document.querySelector("#quick-thought").dispatchEvent(new Event("input",{bubbles:true}));')
  // React controlled input is changed using the native setter in the integration test.
  await capture.webContents.executeJavaScript('const field=document.querySelector("#quick-thought"); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,"value").set.call(field,"Запись через отдельное окно"); field.dispatchEvent(new Event("input",{bubbles:true}));')
  await waitFor(() => capture.webContents.executeJavaScript('!document.querySelector(".calm-primary").disabled'), 'кнопка записи')
  await capture.webContents.executeJavaScript('document.querySelector(".calm-primary").click()')
  await waitFor(async () => (await storage.get()).reminders.some(item => item.title === 'Запись через отдельное окно'), 'сохранение записи')
  await waitFor(() => capture.webContents.executeJavaScript('document.querySelector("#quick-thought").value === ""'), 'подтверждение записи и очистка черновика')
  await window.webContents.executeJavaScript('window.dom.getState()')
  console.log(`Windows: ${exists ? 'повторный запуск и восстановление' : 'первый запуск'}, IPC, шифрование ОС и глобальная запись — OK`)
}
